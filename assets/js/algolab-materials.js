/* =====================================================
   EAGLOPEN — AlgoLab course materials page
   ---------------------------------------------------------------
   Renders the syllabus page from window.ALGOLAB_MATERIALS, which is
   generated by scripts/build-algolab-materials.js.

   Load order matters: this file must run BEFORE assets/js/yt-embed.js so the
   shared .yt-lite video facades already exist when that script binds its
   click handlers on DOMContentLoaded. Course switching is a normal link
   navigation, so facades are never rebuilt client-side.
   ===================================================== */
(() => {
  "use strict";

  const DATA = window.ALGOLAB_MATERIALS;
  const byId = (id) => document.getElementById(id);
  const COURSES = DATA ? DATA.courses : {};

  /* ---------------------------------------------------------- helpers */

  const esc = (value) =>
    String(value == null ? "" : value).replace(
      /[&<>"']/g,
      (char) =>
        ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[char]
    );

  /** Every link that leaves the site opens safely in a new tab. */
  const external = (href) =>
    `href="${esc(href)}" target="_blank" rel="noopener noreferrer"`;

  /* ------------------------------------------------- course selection */

  const queryCourse = new URLSearchParams(location.search).get("course");
  // Unknown or missing values keep falling back to Python, exactly as before.
  const activeCourse = COURSES[queryCourse] ? queryCourse : "python";
  let activeWeek = 0;

  /* --------------------------------------------------- resource rows */

  /**
   * The slots a course actually uses, in the order a student meets them.
   * Derived from the data, so a slot that no lecture has is never rendered -
   * a C++ lecture is never told to expect a notebook.
   */
  function activeSlots(course) {
    const used = new Set();
    for (const lecture of course.lectures) {
      for (const group of lecture.groups) used.add(group.slot);
    }
    return ["notes", "lectureCode", "lab", "problems"].filter((slot) => used.has(slot));
  }

  const SLOT_ICONS = {
    notes: "fas fa-file-lines",
    lectureCode: "fas fa-file-code",
    lab: "fas fa-flask",
    problems: "fas fa-clipboard-list",
  };

  /** Primary and secondary action for each real file, by kind. */
  function fileActions(file) {
    const actions = [];
    if (file.kind === "pdf") {
      actions.push({
        label: "Read Notes",
        icon: "fas fa-book-open",
        href: file.url,
        external: true,
        primary: true,
      });
    }
    if (file.kind === "notebook" && file.colabUrl) {
      actions.push({
        label: "Open in Colab",
        icon: "fab fa-google",
        href: file.colabUrl,
        external: true,
        primary: true,
      });
    }
    actions.push({
      label: file.kind === "pdf" ? "Download" : "Download",
      icon: "fas fa-download",
      href: file.downloadUrl,
      download: true,
      primary: file.kind !== "pdf" && !(file.kind === "notebook" && file.colabUrl),
    });
    if (file.kind === "notebook" && file.previewUrl) {
      actions.push({
        label: "Preview",
        icon: "fas fa-eye",
        href: file.previewUrl,
        external: true,
        tertiary: true,
        hint: "Read-only preview",
      });
    }
    return actions;
  }

  function renderActions(file) {
    return `<div class="al-resource-actions">${fileActions(file)
      .map((action) => {
        const variant = action.tertiary
          ? "al-btn--tertiary"
          : action.primary
            ? "al-btn--primary"
            : "al-btn--onDark";
        const attrs = [
          action.href ? `href="${esc(action.href)}"` : "",
          action.external ? 'target="_blank" rel="noopener noreferrer"' : "",
          action.download ? 'download' : "",
          action.hint ? `title="${esc(action.hint)}"` : "",
          `aria-label="${esc(`${action.label} ${file.name}`)}"`,
        ]
          .filter(Boolean)
          .join(" ");
        return `<a class="al-btn ${variant}" ${attrs}><i class="${action.icon}" aria-hidden="true"></i><span>${esc(
          action.label
        )}</span></a>`;
      })
      .join("")}</div>`;
  }

  function renderFileRow(file) {
    return `<div class="al-resource">
      <span class="al-resource-icon" data-kind="${esc(file.kind)}"><i class="${esc(
      file.icon
    )}" aria-hidden="true"></i></span>
      <div class="al-resource-body">
        <p class="al-resource-name"><span>${esc(file.name)}</span><span class="al-resource-badge">${esc(
      file.badge
    )}</span></p>
        <p class="al-resource-file" title="${esc(file.realName)}">${esc(file.realName)}</p>
      </div>
      ${renderActions(file)}
    </div>`;
  }

  /** The polished "coming soon" state - a missing field picks it automatically. */
  function renderComingSoon(state, extraClass = "") {
    return `<div class="al-coming ${esc(extraClass)}">
      <span class="al-coming-icon"><i class="fas fa-hourglass-half" aria-hidden="true"></i></span>
      <div class="al-coming-text">
        ${state.badge ? `<span class="al-coming-badge">${esc(state.badge)}</span>` : ""}
        <strong>${esc(state.title)}</strong>
        <p>${esc(state.body)}</p>
      </div>
    </div>`;
  }

  /** A slot the course uses that this lecture does not have yet.
      The group heading already names the slot, so no badge is repeated. */
  function renderComingSoonSlot(slot) {
    const { soonTitle, soonBody } = DATA.slots[slot];
    return renderComingSoon({ badge: "", title: soonTitle, body: soonBody });
  }

  /* ------------------------------------------------------- video card */

  /** Exactly the facade the Research page uses, so behaviour cannot drift. */
  function renderPlayer(lecture) {
    return `<div class="yt-lite" data-yt-id="${esc(lecture.videoId)}" data-yt-title="${esc(
      lecture.title
    )}">
      <div class="yt-lite-stage">
        <img src="${esc(lecture.thumbnail)}" alt="Video preview: ${esc(
      lecture.title
    )}" loading="lazy" decoding="async" width="480" height="270" />
        <button class="yt-lite-play" type="button" aria-label="Play: ${esc(
      lecture.title
    )}"><i class="fas fa-play" aria-hidden="true"></i></button>
      </div>
    </div>`;
  }

  function renderLecture(lecture, slots) {
    const groupFor = (slot) => lecture.groups.find((group) => group.slot === slot);

    // Walk the course's slots in the canonical order, so a lecture that has
    // only some of them still reads notes -> code -> lab -> problems.
    const resources = slots
      .map((slot) => {
        const group = groupFor(slot);
        const body = group
          ? group.files.map(renderFileRow).join("")
          : renderComingSoonSlot(slot);
        return `<div class="al-resource-group">
          <h4><i class="${SLOT_ICONS[slot]}" aria-hidden="true"></i>${esc(
          DATA.slots[slot].label
        )}</h4>
          ${body}
        </div>`;
      })
      .join("");

    const video = lecture.videoId
      ? renderPlayer(lecture)
      : renderComingSoon(DATA.comingSoon.video, "al-coming--video");

    return `<article class="al-lecture-card" id="lecture-${lecture.n}">
      <div class="al-lecture-head">
        <span class="al-lecture-num">${esc(String(lecture.n).padStart(2, "0"))}</span>
        <div>
          <h3>${esc(lecture.title)}</h3>
          ${lecture.topic ? `<p class="al-lecture-topic">${esc(lecture.topic)}</p>` : ""}
        </div>
      </div>
      <div class="al-lecture-video">${video}</div>
      <div class="al-lecture-resources">
        ${resources}
        ${
          lecture.extras.length
            ? `<div class="al-resource-group">
                <h4><i class="fas fa-paperclip" aria-hidden="true"></i>Also for this lecture</h4>
                ${lecture.extras.map(renderFileRow).join("")}
              </div>`
            : ""
        }
        ${
          lecture.hasVideo || lecture.hasMaterials
            ? ""
            : `<p class="al-lecture-empty"><strong>${esc(
                DATA.comingSoon.lecture.title
              )}</strong>${esc(DATA.comingSoon.lecture.body)}</p>`
        }
      </div>
    </article>`;
  }

  /* --------------------------------------------------------- team card */

  function renderPerson(slug, badge, badgeClass) {
    const person = DATA.people[slug];
    if (!person) return "";
    const contactLinks = [
      person.linkedin
        ? `<a href="${esc(person.linkedin)}" target="_blank" rel="noopener noreferrer" aria-label="${esc(
            person.name
          )} on LinkedIn"><i class="fa-brands fa-linkedin"></i></a>`
        : "",
      person.email
        ? `<a href="mailto:${esc(
            person.email
          )}" aria-label="Email ${esc(person.name)}"><i class="fa-solid fa-envelope"></i></a>`
        : "",
    ].filter(Boolean);
    const contactHtml = contactLinks.length
      ? `<nav class="al-person-links" aria-label="${esc(
          person.name
        )}'s contact links">${contactLinks.join("")}</nav>`
      : "";
    return `<article class="al-person">
      <div class="al-person-photo">
        <img src="${esc(person.image)}" alt="${esc(person.name)} photo" loading="lazy" width="110" height="110" />
      </div>
      <span class="al-person-role-badge ${badgeClass}">${esc(badge)}</span>
      <h3>${esc(person.name)}</h3>
      <p class="al-person-position">${esc(person.position)}</p>
      <p class="al-person-bio">${esc(person.bio)}</p>
      ${contactHtml}
      ${
        person.profileUrl
          ? `<a class="al-profile-cta" href="${esc(person.profileUrl)}" aria-label="Open ${esc(
              person.name
            )}'s profile"><span>View Profile</span><i class="fa-solid fa-arrow-right" aria-hidden="true"></i></a>`
          : ""
      }
    </article>`;
  }

  function renderTeam(course) {
    byId("course-team-grid").innerHTML = [
      renderPerson(course.instructorKey, "Instructor", "is-instructor"),
      ...DATA.coordinators.map((slug) =>
        renderPerson(slug, "Course Coordinator", "is-coordinator")
      ),
    ].join("");
  }

  /* ------------------------------------------------------- directions */

  const PDF_CARD = {
    icon: "fas fa-file-pdf",
    title: "Read the notes (PDF)",
    body:
      "Click <strong>Read Notes</strong> to open the lecture notes right here in your browser. You can also download them to read offline.",
  };

  const NOTEBOOK_CARD = {
    icon: "fas fa-file-code",
    title: "Run the code and labs (.ipynb)",
    options: [
      {
        title: "Option 1: Google Colab",
        note: "No installation needed",
        steps: [
          "Click <strong>Open in Colab</strong> on any notebook below and it runs straight away in your browser.",
          "No button? Go to <strong>colab.research.google.com</strong>, choose <strong>File &rarr; Upload notebook</strong> and select the downloaded <code>.ipynb</code> file.",
          "Sign in with a Google account, then run each cell with <kbd>Shift + Enter</kbd>.",
        ],
        cta: { label: "Open Google Colab", href: "https://colab.research.google.com/" },
      },
      {
        title: "Option 2: Jupyter Notebook",
        note: "On your computer",
        steps: [
          "Download the <code>.ipynb</code> file with the <strong>Download</strong> button.",
          "Install Jupyter &mdash; for example through <strong>Anaconda</strong>, or with <code>pip install notebook</code>.",
          "Run <code>jupyter notebook</code> in that folder and open the file from the list.",
        ],
        cta: { label: "Jupyter install guide", href: "https://jupyter.org/install" },
      },
    ],
  };

  const SLIDES_CARD = {
    icon: "fas fa-file-powerpoint",
    title: "Open the lecture slides (PowerPoint)",
    body:
      "Slides arrive as PowerPoint decks. Click <strong>Download</strong> to save one, then open it in PowerPoint, Google Slides or LibreOffice Impress &mdash; it works offline once downloaded.",
    link: { label: "Open Google Slides", href: "https://slides.google.com/" },
  };

  function renderHowTo(course) {
    const kinds = course.kinds;
    const cards = [];

    if (kinds.includes("pdf")) cards.push(PDF_CARD);
    if (kinds.includes("notebook")) cards.push(NOTEBOOK_CARD);
    if (kinds.includes("slides")) cards.push(SLIDES_CARD);

    const html = cards
      .map((card) => {
        const inner = card.options
          ? `<div class="al-howto-options">${card.options
              .map(
                (option, index) => `<div class="al-howto-option">
                  <h4><span aria-hidden="true">${index + 1}</span>${esc(option.title)}</h4>
                  <p class="al-howto-sub">${esc(option.note)}</p>
                  <ol>${option.steps.map((step) => `<li>${step}</li>`).join("")}</ol>
                  <a class="al-btn al-btn--ghost" ${external(option.cta.href)}><i class="fas fa-arrow-right" aria-hidden="true"></i><span>${esc(
                  option.cta.label
                )}</span></a>
                </div>`
              )
              .join("")}</div>`
          : card.link
            ? `<a class="al-btn al-btn--ghost" ${external(card.link.href)}><i class="fas fa-arrow-right" aria-hidden="true"></i><span>${esc(
                card.link.label
              )}</span></a>`
            : "";

        return `<div class="al-howto-card">
          <div class="al-howto-head">
            <span class="al-howto-icon"><i class="${card.icon}" aria-hidden="true"></i></span>
            <h3>${esc(card.title)}</h3>
          </div>
          ${card.body ? `<p>${card.body}</p>` : ""}
          ${inner}
        </div>`;
      })
      .join("");

    // Say what this course actually has, rather than a generic line.
    const has = (kind) => kinds.includes(kind);
    const tip = has("notebook")
      ? "Not sure which to pick? Start with Google Colab; nothing to install."
      : has("pdf") && has("slides")
        ? "Everything here is a PDF or a slide deck: download it once and it works offline."
        : has("pdf")
          ? "Everything here is a PDF: download it once and it works offline."
          : has("slides")
            ? "Everything here is a slide deck: download it once and it works offline."
            : "Download any file once and it works offline.";

    byId("course-howto-grid").innerHTML = html;
    byId("course-howto-tip").innerHTML =
      `<i class="fas fa-lightbulb" aria-hidden="true"></i><span>${esc(tip)}</span>`;
  }

  /* ------------------------------------------------------------ extras */

  function renderExtras(course) {
    const host = byId("course-extras");
    if (!course.extras.length) {
      host.innerHTML = "";
      host.hidden = true;
      return;
    }
    host.hidden = false;
    host.innerHTML = `<h3><i class="fas fa-folder-open" aria-hidden="true"></i>Course resources</h3>
      <p>Reference material that is not tied to a single lecture.</p>
      ${course.extras.map(renderFileRow).join("")}`;
  }

  /* ---------------------------------------------------------- syllabus */

  function renderWeek(index) {
    activeWeek = index;
    const course = COURSES[activeCourse];

    byId("week-nav").querySelectorAll("[data-week]").forEach((button) => {
      button.classList.toggle("is-active", Number(button.dataset.week) === index);
    });

    byId("day-grid").innerHTML = course.weeks[index]
      .map((topic, dayIndex) => {
        const day = dayIndex + 1;
        const globalDay = index * course.days.length + day;
        return `<article class="al-day-card">
          <div class="al-day-heading">
            <span>Day ${globalDay}</span>
            <p>${esc(course.days[dayIndex])} &middot; ${esc(course.time)}</p>
            <h3>${esc(topic)}</h3>
          </div>
        </article>`;
      })
      .join("");
  }

  function renderSyllabus(course) {
    byId("week-nav").innerHTML = course.weeks
      .map(
        (week, index) => `<button class="${index === 0 ? "is-active" : ""}" type="button" data-week="${index}">
          <span>Week ${index + 1}</span>
          <small>${
            index === 0 ? "Foundations" : index === 1 ? "Build skills" : "Create &amp; apply"
          }</small>
        </button>`
      )
      .join("");

    byId("week-nav")
      .querySelectorAll("[data-week]")
      .forEach((button) =>
        button.addEventListener("click", () => {
          renderWeek(Number(button.dataset.week));
          byId("week-nav").scrollIntoView({ behavior: "smooth", block: "nearest" });
        })
      );

    renderWeek(0);
  }

  /* -------------------------------------------------------------- main */

  function render() {
    const course = COURSES[activeCourse];
    const slots = activeSlots(course);

    document.title = `${course.name} Materials | EAGLOPEN`;

    // Course switcher - plain links, so switching reloads the page.
    byId("course-tabs").innerHTML = Object.entries(COURSES)
      .map(
        ([key, item]) =>
          `<a class="al-course-tab ${key === activeCourse ? "is-active" : ""}" href="algolab-materials.html?course=${key}"><i class="${
            item.icon
          }" aria-hidden="true"></i><span>${esc(item.name)}</span></a>`
      )
      .join("");

    const fileCount =
      course.extras.length +
      course.lectures.reduce(
        (total, lecture) =>
          total +
          lecture.groups.reduce((n, group) => n + group.files.length, 0) +
          lecture.extras.length,
        0
      );

    byId("course-overview").innerHTML = `<div class="al-course-mark"><i class="${course.icon}" aria-hidden="true"></i></div>
      <div>
        <p class="al-course-label">${esc(course.days.join(" · "))} &middot; ${esc(course.time)}</p>
        <h2>${esc(course.name)}</h2>
        <p>${esc(course.summary)}</p>
      </div>
      <div class="al-course-stats">
        <span><strong>${course.weeks.length}</strong> weeks</span>
        <span><strong>${course.lectures.length}</strong> lectures</span>
        <span><strong>${fileCount}</strong> files</span>
      </div>`;

    renderTeam(course);
    renderCredit(course);
    renderHowTo(course);

    byId("videos-eyebrow").textContent = course.videoLibrary.eyebrow;
    byId("videos-title").textContent = course.videoLibrary.heading;
    byId("videos-sub").textContent = course.videoLibrary.description;
    byId("lecture-grid").innerHTML = course.lectures
      .map((lecture) => renderLecture(lecture, slots))
      .join("");

    renderExtras(course);
    renderSyllabus(course);
  }

  /** Python only. The credit is about the materials, never about the videos. */
  function renderCredit(course) {
    const host = byId("course-credit");
    const line = byId("videos-credit");
    if (!course.credit) {
      host.innerHTML = "";
      host.hidden = true;
      line.innerHTML = "";
      line.hidden = true;
      return;
    }

    host.hidden = false;
    host.innerHTML = `<div class="al-credit">
      <span class="al-credit-mark"><i class="fas fa-award" aria-hidden="true"></i></span>
      <div>
        <span class="al-credit-eyebrow">${esc(course.credit.eyebrow)}</span>
        <h2 id="course-credit-title">${esc(course.credit.heading)}</h2>
        <p>${esc(course.credit.body)}</p>
        <a class="al-credit-link" ${external(course.credit.linkHref)}><span>${esc(
      course.credit.linkLabel
    )}</span><i class="fas fa-arrow-right" aria-hidden="true"></i></a>
      </div>
    </div>`;

    line.hidden = false;
    line.innerHTML = `<i class="fas fa-award" aria-hidden="true"></i><span>${esc(
      course.credit.materialsLine
    )}</span>`;
  }

  if (DATA && COURSES[activeCourse]) render();
})();